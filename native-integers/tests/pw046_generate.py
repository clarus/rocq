#!/usr/bin/env python3
"""Generate PW046 independent corpora and exactly sixty evaluator witnesses."""

from __future__ import annotations

import argparse
import hashlib
import importlib.util
import json
from pathlib import Path


WIDTHS = (8, 16, 32, 64, 128, 256)


def load(name: str, path: Path):
    spec = importlib.util.spec_from_file_location(name, path)
    if spec is None or spec.loader is None:
        raise SystemExit(f"cannot load {path}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def zlist(values: list[int]) -> str:
    return "[" + "; ".join(map(str, values)) + "]%Z"


def edge_definition() -> str:
    rows: list[str] = []
    for width in (128, 256):
        word = f"Word{width}"
        signed_max = (1 << (width - 1)) - 1
        rows.extend(
            [
                f"match {word}.divu {word}.one {word}.zero with None => true | Some _ => false end",
                f"match {word}.modu {word}.one {word}.zero with None => true | Some _ => false end",
                f"match {word}.divmodu {word}.one {word}.zero with None => true | Some _ => false end",
                f"match {word}.divs_checked {word}.min_signed {word}.max_unsigned with None => true | Some _ => false end",
                f"match {word}.neg_checked {word}.min_signed with None => true | Some _ => false end",
                f"match {word}.add_checked ({word}.of_Z {signed_max}) {word}.one with None => true | Some _ => false end",
                f"{word}.eqb ({word}.shift_right_signed ({word}.of_Z 3) {word}.max_unsigned) ({word}.of_Z 6)",
                f"{word}.eqb ({word}.shift_left_signed ({word}.of_Z 4) {word}.max_unsigned) ({word}.of_Z 2)",
                f"{word}.eqb ({word}.shift_right_signed ({word}.of_Z (-1)) {word}.one) {word}.max_unsigned",
                f"{word}.eqb ({word}.Raw.divu {word}.one {word}.zero) {word}.zero",
                f"{word}.eqb ({word}.Raw.modu ({word}.of_Z 7) {word}.zero) ({word}.of_Z 7)",
            ]
        )
    return "Definition pw046_wide_failure_and_signed_edges : list bool :=\n  [ " + \
        "\n  ; ".join(rows) + " ].\n"


def evaluator_source(oracle) -> tuple[str, dict[str, int]]:
    chunks = ["""(* Generated by pw046_generate.py from the independent PW031 oracle. *)
From Stdlib Require Import ZArith List.
From Rocq.PrimitiveWords Require Import
  Word8 Word16 Word32 Word64 Word128 Word256 PW031Campaign PW032Matrix.
Import ListNotations.
Open Scope Z_scope.
""", edge_definition()]
    counts = {
        "complete_rows": 0,
        "normalized_wide": 0,
        "conversions": 0,
        "cross_width": 0,
        "wide_edge_aggregates": 0,
    }

    for width in WIDTHS:
        maximum = (1 << width) - 1
        expected = (
            f"({zlist(oracle.raw_row(width, maximum, 1))}, "
            f"({zlist(oracle.public_row(width, maximum, 1, 1))}, "
            f"{zlist(oracle.meta_row(width, maximum, 1, 1))}))"
        )
        term = (
            f"(pw031_raw{width} {maximum} 1, "
            f"(pw031_public{width} {maximum} 1 1, "
            f"pw031_meta{width} {maximum} 1 1))"
        )
        for engine, tactic in (("cbv", "cbv"), ("vm", "vm_compute")):
            chunks.append(
                f"Example pw046_complete_{width}_{engine} :\n"
                f"  {term} = {expected}.\nProof. {tactic}. reflexivity. Qed.\n"
            )
            counts["complete_rows"] += 1

    for width in (128, 256):
        maximum = (1 << width) - 1
        divisor = (1 << (width - 1)) + 3
        expected = oracle.raw_row(width, maximum, divisor)
        expected += oracle.public_row(width, maximum, divisor, 1)
        term = (
            f"pw031_raw{width} {maximum} {divisor} ++ "
            f"pw031_public{width} {maximum} {divisor} 1"
        )
        for engine, tactic in (("cbv", "cbv"), ("vm", "vm_compute")):
            chunks.append(
                f"Example pw046_normalized_{width}_{engine} :\n"
                f"  {term} = {zlist(expected)}.\n"
                f"Proof. {tactic}. reflexivity. Qed.\n"
            )
            counts["normalized_wide"] += 1

    for width in WIDTHS:
        boundary = 1 << width
        expected = oracle.conversion_row(width, -1, boundary, width + 1)
        term = f"pw031_conversion{width} (-1) {boundary} {width + 1}"
        for engine, tactic in (("cbv", "cbv"), ("vm", "vm_compute")):
            chunks.append(
                f"Example pw046_conversion_{width}_{engine} :\n"
                f"  {term} = {zlist(expected)}.\n"
                f"Proof. {tactic}. reflexivity. Qed.\n"
            )
            counts["conversions"] += 1

    for index, src in enumerate(WIDTHS):
        for dst in WIDTHS[index + 1 :]:
            expected = oracle.cross_row(src, dst, -1)
            term = f"pw031_cross_{src}_{dst} (-1)"
            for engine, tactic in (("cbv", "cbv"), ("vm", "vm_compute")):
                chunks.append(
                    f"Example pw046_cross_{src}_{dst}_{engine} :\n"
                    f"  {term} = {zlist(expected)}.\n"
                    f"Proof. {tactic}. reflexivity. Qed.\n"
                )
                counts["cross_width"] += 1

    expected_edges = "[" + "; ".join(["true"] * 22) + "]"
    for engine, tactic in (("cbv", "cbv"), ("vm", "vm_compute")):
        chunks.append(
            f"Example pw046_wide_edges_{engine} :\n"
            f"  pw046_wide_failure_and_signed_edges = {expected_edges}.\n"
            f"Proof. {tactic}. reflexivity. Qed.\n"
        )
        counts["wide_edge_aggregates"] += 1

    chunks.append("""Print Assumptions pw046_complete_8_cbv.
Print Assumptions pw046_complete_256_vm.
Print Assumptions pw046_wide_edges_cbv.
Print Assumptions pw046_wide_edges_vm.
""")
    if sum(counts.values()) != 60:
        raise SystemExit(f"evaluator witness cardinality drift: {counts}")
    return "\n".join(chunks), counts


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--pw031", required=True, type=Path)
    parser.add_argument("--pw032", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    args = parser.parse_args()
    output = args.output.resolve()
    output.mkdir(parents=True, exist_ok=True)
    pw031 = load("pw046_pw031", args.pw031.resolve())
    pw032 = load("pw046_pw032", args.pw032.resolve())

    independent = pw031.generate(output)
    expected_rows = pw032.write_expected(pw031, output / "pw032-expected.tsv")
    matrix_rows = pw032.write_matrix(output / "pw032-coverage.tsv")
    source, counts = evaluator_source(pw031)
    evaluator = output / "PW046Evaluators.v"
    evaluator.write_text(source, encoding="utf-8")
    summary = {
        "schema": "Gecko/PW046/generated-correctness/v1",
        "widths": list(WIDTHS),
        "pw031_rows": independent["constant_rows"] + independent["raw_rows"]
        + independent["conversion_rows"] + independent["cross_rows"],
        "pw031_property_checks": independent["oracle_property_checks"],
        "pw031_vectors_sha256": independent["vectors_sha256"],
        "pw031_oracle_sha256": independent["oracle_sha256"],
        "pw031_coverage_rows": independent["coverage_rows"],
        "pw032_expected_rows": expected_rows,
        "pw032_matrix_rows": matrix_rows,
        "evaluator_witnesses": sum(counts.values()),
        "evaluator_categories": counts,
        "wide_edge_booleans": 22,
        "evaluator_sha256": hashlib.sha256(evaluator.read_bytes()).hexdigest(),
        "pw032_expected_sha256": hashlib.sha256(
            (output / "pw032-expected.tsv").read_bytes()
        ).hexdigest(),
        "pw032_coverage_sha256": hashlib.sha256(
            (output / "pw032-coverage.tsv").read_bytes()
        ).hexdigest(),
    }
    (output / "pw046-generation.json").write_text(
        json.dumps(summary, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )
    print(json.dumps(summary, sort_keys=True))


if __name__ == "__main__":
    main()
